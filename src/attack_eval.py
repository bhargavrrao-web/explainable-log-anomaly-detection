"""STEP E: test the pipeline on a SYNTHETIC SSH auth.log with an injected brute-force attack.

!! EVERYTHING HERE IS SYNTHETIC. The log is generated by this script (random but seeded); it is NOT
!! real attack data and NOT a real system's log. Results show the pipeline reacts to a *simulated*
!! pattern, not that it would catch real intrusions. Attacker IPs use 203.0.113.0/24 (RFC 5737
!! documentation range), so nothing here refers to a real host.

Scenarios injected in the TEST part of the timeline (chronological split, train = normal only):
  fast_burst : ~120 failed-password lines within ~2 minutes from one IP (classic brute force)
  slow_drip  : 25 failed attempts spread across ~2 hours among normal traffic (hard case)

Run:  python src/attack_eval.py
"""
import random
import sys
from datetime import datetime, timedelta
from pathlib import Path

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np
import pandas as pd

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))
from src.models.emb_models import EmbIForest, EmbLSTM
from src.pipeline import load_model, parse_and_window, strip_prefix
from src.utils import load_config, p, set_seed

HOST = "labhost"
USERS = ["alice", "bob", "carol", "dave"]
BASE = datetime(2026, 3, 2, 8, 0, 0)  # arbitrary fixed date; synthetic
HEADER = "# SYNTHETIC auth.log generated by src/attack_eval.py -- NOT real data. Attacker IPs are RFC5737 documentation addresses."


def _line(ts, proc, pid, msg):
    return f"{ts.strftime('%b %e %H:%M:%S')} {HOST} {proc}[{pid}]: {msg}"


def generate(seed=42, n_normal_sessions=420):
    """Returns list of (timestamp, line, is_attack, scenario). Sorted by time."""
    rnd = random.Random(seed)
    rows = []
    span = timedelta(hours=40)
    sid = 100
    for _ in range(n_normal_sessions):                      # ---- normal SSH sessions
        t = BASE + timedelta(seconds=rnd.uniform(0, span.total_seconds()))
        user, ip = rnd.choice(USERS), f"192.168.1.{rnd.randint(10, 40)}"
        port, pid, sid = rnd.randint(40000, 60000), rnd.randint(1000, 30000), sid + 1
        if rnd.random() < 0.07:                              # benign typo: one failed password, then success
            rows.append((t, _line(t, "sshd", pid, f"Failed password for {user} from {ip} port {port} ssh2"), 0, ""))
            t += timedelta(seconds=4)
        auth = "publickey" if rnd.random() < 0.6 else "password"
        rows.append((t, _line(t, "sshd", pid, f"Accepted {auth} for {user} from {ip} port {port} ssh2"), 0, ""))
        rows.append((t, _line(t, "sshd", pid, f"pam_unix(sshd:session): session opened for user {user}(uid=1000) by (uid=0)"), 0, ""))
        rows.append((t, _line(t, "systemd-logind", pid + 1, f"New session {sid} of user {user}."), 0, ""))
        end = t + timedelta(minutes=rnd.uniform(1, 90))
        rows.append((end, _line(end, "sshd", pid, f"Received disconnect from {ip} port {port}:11: disconnected by user"), 0, ""))
        rows.append((end, _line(end, "sshd", pid, f"pam_unix(sshd:session): session closed for user {user}"), 0, ""))
        rows.append((end, _line(end, "systemd-logind", pid + 1, f"Removed session {sid}."), 0, ""))
        if rnd.random() < 0.5:                               # background cron noise
            c = t + timedelta(minutes=rnd.uniform(0, 30))
            rows.append((c, _line(c, "CRON", pid + 5, "pam_unix(cron:session): session opened for user root(uid=0) by (uid=0)"), 0, ""))
            rows.append((c + timedelta(seconds=2), _line(c, "CRON", pid + 5, "pam_unix(cron:session): session closed for user root"), 0, ""))

    # ---- injected attacks (labelled) ----
    t0 = BASE + span * 0.80
    atk_ip = "203.0.113.45"
    for i in range(120):
        t = t0 + timedelta(seconds=i * rnd.uniform(0.5, 1.5))
        user = rnd.choice(["root", "admin", "test", "oracle", "ubuntu", "postgres"])
        port, pid = rnd.randint(30000, 65000), rnd.randint(30000, 31000)
        rows.append((t, _line(t, "sshd", pid, f"Failed password for invalid user {user} from {atk_ip} port {port} ssh2"), 1, "fast_burst"))
        if i % 3 == 0:
            rows.append((t, _line(t, "sshd", pid, f"Connection closed by authenticating user {user} {atk_ip} port {port} [preauth]"), 1, "fast_burst"))
    t1 = BASE + span * 0.90
    for i in range(25):
        t = t1 + timedelta(minutes=i * rnd.uniform(3, 6))
        port, pid = rnd.randint(30000, 65000), rnd.randint(31000, 32000)
        rows.append((t, _line(t, "sshd", pid, f"Failed password for invalid user admin from 198.51.100.7 port {port} ssh2"), 1, "slow_drip"))
    rows.sort(key=lambda r: r[0])
    return rows


def main():
    cfg = load_config()
    set_seed(cfg["seed"])
    out_dir = p("data/synthetic")
    out_dir.mkdir(parents=True, exist_ok=True)
    rows = generate(cfg["seed"])
    log = out_dir / "SYNTHETIC_auth.log"
    log.write_text(HEADER + "\n" + "\n".join(r[1] for r in rows) + "\n", encoding="utf-8")
    pd.DataFrame({"line_no": range(len(rows)), "is_attack": [r[2] for r in rows], "scenario": [r[3] for r in rows]}) \
        .to_csv(out_dir / "SYNTHETIC_auth_labels.csv", index=False)
    print(f"Wrote {log.name}: {len(rows)} lines, {sum(r[2] for r in rows)} injected attack lines "
          f"({sum(r[3] == 'fast_burst' for r in rows)} fast_burst, {sum(r[3] == 'slow_drip' for r in rows)} slow_drip)")
    print("sample:", rows[0][1], "\n       ", [r[1] for r in rows if r[2]][0])

    # ---- same pipeline as the dashboard upload page ----
    lines = [strip_prefix(r[1]) for r in rows]
    is_atk = np.array([r[2] for r in rows])
    scen = np.array([r[3] for r in rows])
    cut = int(len(lines) * cfg["data"]["train_fraction"])          # chronological split
    assert not is_atk[:cut].any(), "attack lines leaked into the TRAIN portion"   # guard against contamination
    W, S = cfg["bgl"]["window_size"], cfg["bgl"]["step"]
    ids, templates, emb, _ = parse_and_window(lines, cfg)
    print(f"Drain found {len(templates)} templates, e.g.:")
    for t in list(templates.values())[:4]:
        print("   ", t[:90])

    def windows(a, b):
        return [(s, ids[s:s + W]) for s in range(a, b - W + 1, S)]
    tr_w, te_w = windows(0, cut), windows(cut, len(lines))
    tr_seqs, te_seqs = [w for _, w in tr_w], [w for _, w in te_w]
    te_lab = np.array([int(is_atk[s:s + W].any()) for s, _ in te_w])
    te_scn = np.array([next((x for x in scen[s:s + W] if x), "") for s, _ in te_w])
    print(f"train windows: {len(tr_w)} (all normal, verified attack-free) | "
          f"test windows: {len(te_w)} of which attack: {te_lab.sum()} "
          f"(fast_burst {(te_scn == 'fast_burst').sum()}, slow_drip {(te_scn == 'slow_drip').sum()})")

    # ---- models: (a) trained on HDFS/BGL and transferred, (b) trained on this SSH log's normal part ----
    l = cfg["lstm"]
    models = {}
    for src in ["HDFS", "BGL"]:
        for name in ["EmbLSTM", "EmbIForest"]:
            models[f"{name} (trained on {src})"] = load_model(name, src)
    models["EmbIForest (trained on SSH-normal)"] = EmbIForest(cfg["iforest"]["n_estimators"], cfg["seed"]).fit(tr_seqs, emb)
    models["EmbLSTM (trained on SSH-normal)"] = EmbLSTM(l["hidden_size"], l["num_layers"], l["batch_size"], l["epochs"],
                                                        l["lr"], min(l["window"], 10), cfg["seed"]).fit(tr_seqs, emb)

    res, win_rows = [], pd.DataFrame({"window_start_line": [s for s, _ in te_w], "attack": te_lab, "scenario": te_scn})
    for name, m in models.items():
        m.calibrate(tr_seqs, emb, cfg["iforest"]["threshold_percentile"])   # threshold from the target's normal windows
        sc = m.score(te_seqs, emb)
        fl = sc > m.threshold
        win_rows[name] = sc
        tp, fp = int((fl & (te_lab == 1)).sum()), int((fl & (te_lab == 0)).sum())
        n_atk, n_norm = int(te_lab.sum()), int((te_lab == 0).sum())
        r = dict(model=name, attack_windows=n_atk, flagged_attack=tp, detection_rate=round(tp / n_atk, 3),
                 normal_windows=n_norm, false_alarms=fp, false_alarm_rate=round(fp / n_norm, 3),
                 precision=round(tp / max(1, tp + fp), 3),
                 fast_burst_detected=f"{int((fl & (te_scn == 'fast_burst')).sum())}/{int((te_scn == 'fast_burst').sum())}",
                 slow_drip_detected=f"{int((fl & (te_scn == 'slow_drip')).sum())}/{int((te_scn == 'slow_drip').sum())}",
                 roc_auc=round(float(__import__('sklearn.metrics', fromlist=['x']).roc_auc_score(te_lab, sc)), 3))
        res.append(r)
    df = pd.DataFrame(res)
    pd.set_option("display.width", 250, "display.max_columns", 20)
    print("\n", df.to_string(index=False))
    rdir = p(cfg["paths"]["results_dir"])
    df.to_csv(rdir / "attack_eval.csv", index=False)
    win_rows.round(4).to_csv(rdir / "attack_windows.csv", index=False)

    # ---- plot: score timeline for the two most relevant models ----
    pick = ["EmbLSTM (trained on SSH-normal)", "EmbIForest (trained on SSH-normal)", "EmbLSTM (trained on HDFS)"]
    fig, axes = plt.subplots(len(pick), 1, figsize=(9, 2.4 * len(pick)), sharex=True)
    x = win_rows.window_start_line.values
    for ax, nm in zip(axes, pick):
        ax.plot(x, win_rows[nm], color="#4C78A8", lw=1)
        ax.axhline(models[nm].threshold, color="#444", ls="--", lw=1, label="threshold")
        ax.scatter(x[te_lab == 1], win_rows[nm][te_lab == 1], color="#D55E00", s=14, label="window contains injected attack", zorder=3)
        ax.set_title(nm, fontsize=9)
        ax.spines[["top", "right"]].set_visible(False)
    axes[0].legend(fontsize=7)
    axes[-1].set_xlabel("first line of window (SYNTHETIC log, test portion)")
    plt.tight_layout()
    plt.savefig(rdir / "attack_scores.png", dpi=130)
    print("\nSaved results/attack_eval.csv, attack_windows.csv, attack_scores.png")


if __name__ == "__main__":
    main()
