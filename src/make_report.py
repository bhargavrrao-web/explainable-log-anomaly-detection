"""STEP F helper: collect every results CSV into ONE markdown file (results/results_tables.md).
No numbers are typed by hand - everything is read from the CSVs written by the experiments.
Run:  python src/make_report.py
"""
import sys
from pathlib import Path

import pandas as pd

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))
from src.utils import load_config, p


def md(df):
    """Tiny DataFrame -> markdown table (avoids the optional 'tabulate' dependency)."""
    cols = list(df.columns)
    out = ["| " + " | ".join(map(str, cols)) + " |", "|" + "---|" * len(cols)]
    for _, r in df.iterrows():
        out.append("| " + " | ".join(f"{v:.3f}" if isinstance(v, float) else str(v) for v in r) + " |")
    return "\n".join(out)


def main():
    res = p(load_config()["paths"]["results_dir"])
    base = pd.read_csv(res / "metrics.csv")
    cross = pd.read_csv(res / "cross_dataset.csv")
    sens = pd.read_csv(res / "cross_dataset_threshold_sensitivity.csv")
    atk = pd.read_csv(res / "attack_eval.csv")
    f1 = cross.pivot(index="model", columns="experiment", values="f1")[["HDFS->HDFS", "BGL->BGL", "HDFS->BGL", "BGL->HDFS"]].round(3).reset_index()
    auc = cross.pivot(index="model", columns="experiment", values="roc_auc")[["HDFS->HDFS", "BGL->BGL", "HDFS->BGL", "BGL->HDFS"]].round(3).reset_index()
    sp = sens.pivot_table(index=["model", "experiment"], columns="percentile", values="f1").round(3).reset_index()
    text = f"""# Results tables (auto-generated by src/make_report.py from results/*.csv)

## 1. In-dataset baselines, event-ID features (Step B)
{md(base.drop(columns=['train_seconds']))}

## 2. Embedding models: F1 per experiment (Step C, 95th-percentile threshold)
{md(f1)}

## 3. Embedding models: ROC-AUC per experiment (threshold-free)
{md(auc)}

## 4. F1 vs calibration percentile (threshold sensitivity)
{md(sp)}

## 5. SYNTHETIC SSH brute-force test (Step E)
{md(atk)}
"""
    (res / "results_tables.md").write_text(text, encoding="utf-8")
    print(text)


if __name__ == "__main__":
    main()
